def is_palindrome(s):
    return s == s[::-1]
''' check if a given string is a palindrome. return true it is, 
false'''

def count_words(text):
    return len(text.split())
'''count the number of words in the given text. return the count as an
integer'''

def celsius_to_fahrenheit(c):
    return (c * 9/5) + 32 
'''convert a temperature value from celsius to fahrenheit. return
the temperature in fahrenheit.'''

